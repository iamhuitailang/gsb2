#!/usr/bin/env python3
"""生成带凹槽与多材质面的示例网格（OBJ + MTL）。

几何：一个 6 x 4 的块体，上表面有两条下沉的矩形凹槽（沟槽），
并按语义分配 4 种材质：
  base_sides   侧壁与底面
  top_panels   上表面平台
  groove_walls 凹槽内壁
  groove_floor 凹槽底面

输出到仓库根目录的 assets/（与本脚本所在目录分离）。
只用标准库；以 `python3 -I tools/generate_sample_mesh.py` 运行。
"""

import argparse
import os
import sys

# ---- 参数化尺寸 ----
NX, NY = 12, 8          # 上表面网格分辨率
LX, LY = 6.0, 4.0       # 块体长、宽
BOTTOM_Z = -1.0         # 底面高度
# 两条凹槽：x 区间 (x0,x1)、y 区间 (y0,y1)、槽底高度
GROOVES = [
    (1.2, 2.0, 0.4, 3.6, -0.55),
    (3.8, 4.6, 0.4, 3.6, -0.55),
]
MATERIALS = [
    ("base_sides",   (0.32, 0.34, 0.40)),
    ("top_panels",   (0.72, 0.70, 0.62)),
    ("groove_walls", (0.85, 0.45, 0.20)),
    ("groove_floor", (0.20, 0.55, 0.78)),
]


def in_groove(x, y):
    """返回该 (x,y) 柱位所属凹槽编号（1 起），不在凹槽返回 0。"""
    for i, (x0, x1, y0, y1, _) in enumerate(GROOVES, start=1):
        if x0 <= x <= x1 and y0 <= y <= y1:
            return i
    return 0


def top_height(x, y):
    for x0, x1, y0, y1, zf in GROOVES:
        if x0 <= x <= x1 and y0 <= y <= y1:
            return zf
    return 0.0


def build_mesh():
    dx, dy = LX / NX, LY / NY
    xs = [i * dx for i in range(NX + 1)]
    ys = [j * dy for j in range(NY + 1)]

    # 顶点表（去重）：同一 (x,y) 柱在高度变化处需要多个顶点，
    # 键为 (x, y, z)
    verts = {}
    vlist = []

    def vid(x, y, z):
        key = (round(x, 9), round(y, 9), round(z, 9))
        if key not in verts:
            verts[key] = len(vlist)
            vlist.append(key)
        return verts[key]

    faces = []  # (材质id, [v1,v2,v3])

    # ---- 上表面（含凹槽底面），按格子三角化 ----
    grid = [[None] * (NY + 1) for _ in range(NX + 1)]
    for i, x in enumerate(xs):
        for j, y in enumerate(ys):
            grid[i][j] = vid(x, y, top_height(x, y))

    for i in range(NX):
        for j in range(NY):
            cx = (xs[i] + xs[i + 1]) / 2
            cy = (ys[j] + ys[j + 1]) / 2
            g = in_groove(cx, cy)
            mat = 3 if g else 1  # groove_floor : top_panels
            a, b = grid[i][j], grid[i + 1][j]
            c, d = grid[i + 1][j + 1], grid[i][j + 1]
            faces.append((mat, [a, b, c]))
            faces.append((mat, [a, c, d]))

    # ---- 凹槽内壁：沿每条凹槽的四条边，从平台 z=0 垂到槽底 ----
    for x0, x1, y0, y1, zf in GROOVES:
        # 4 条侧壁的柱位序列（x 或 y 固定，沿另一方向步进）
        walls = [
            ("x", x0, [(y0 + k * dy) for k in range(int(round((y1 - y0) / dy)) + 1)]),
            ("x", x1, [(y0 + k * dy) for k in range(int(round((y1 - y0) / dy)) + 1)]),
            ("y", y0, [(x0 + k * dx) for k in range(int(round((x1 - x0) / dx)) + 1)]),
            ("y", y1, [(x0 + k * dx) for k in range(int(round((x1 - x0) / dx)) + 1)]),
        ]
        for axis, fixed, along in walls:
            for k in range(len(along) - 1):
                t0, t1 = along[k], along[k + 1]
                if axis == "x":
                    p0t, p1t = (fixed, t0), (fixed, t1)
                else:
                    p0t, p1t = (t0, fixed), (t1, fixed)
                top0 = vid(*p0t, 0.0)
                top1 = vid(*p1t, 0.0)
                bot0 = vid(*p0t, zf)
                bot1 = vid(*p1t, zf)
                faces.append((2, [top0, bot0, bot1]))
                faces.append((2, [top0, bot1, top1]))

    # ---- 侧壁（四条外边，从 z=0 到 BOTTOM_Z）与底面 ----
    perimeter = (
        [("y", 0.0, xs)] +
        [("x", LX, ys)] +
        [("y", LY, list(reversed(xs)))] +
        [("x", 0.0, list(reversed(ys)))]
    )
    bottom_vids = {}
    for axis, fixed, along in perimeter:
        for k in range(len(along) - 1):
            t0, t1 = along[k], along[k + 1]
            p0 = (fixed, t0) if axis == "x" else (t0, fixed)
            p1 = (fixed, t1) if axis == "x" else (t1, fixed)
            top0 = vid(*p0, 0.0)
            top1 = vid(*p1, 0.0)
            b0 = vid(*p0, BOTTOM_Z)
            b1 = vid(*p1, BOTTOM_Z)
            bottom_vids[p0] = b0
            bottom_vids[p1] = b1
            faces.append((0, [top0, b0, b1]))
            faces.append((0, [top0, b1, top1]))

    # 底面：用四个角扇出
    corners = [(0.0, 0.0), (LX, 0.0), (LX, LY), (0.0, LY)]
    cb = [vid(x, y, BOTTOM_Z) for x, y in corners]
    center = vid(LX / 2, LY / 2, BOTTOM_Z)
    for k in range(4):
        faces.append((0, [center, cb[k], cb[(k + 1) % 4]]))

    return vlist, faces


def write_obj(vlist, faces, obj_path, mtl_name):
    lines = ["# Sample mesh generated by tools/generate_sample_mesh.py",
             f"mtllib {mtl_name}", ""]
    for x, y, z in vlist:
        lines.append(f"v {x:.6f} {y:.6f} {z:.6f}")
    lines.append("")
    last_mat = -1
    for mat_id, tri in faces:
        if mat_id != last_mat:
            lines.append(f"usemtl {MATERIALS[mat_id][0]}")
            last_mat = mat_id
        lines.append("f " + " ".join(str(i + 1) for i in tri))
    with open(obj_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_mtl(mtl_path):
    lines = ["# Materials for sample mesh", ""]
    for name, (r, g, b) in MATERIALS:
        lines.append(f"newmtl {name}")
        lines.append(f"Kd {r} {g} {b}")
        lines.append("")
    with open(mtl_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", default=None,
                    help="输出目录，默认 <仓库根>/assets")
    args = ap.parse_args()
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_dir = args.out or os.path.join(repo_root, "assets")
    os.makedirs(out_dir, exist_ok=True)

    vlist, faces = build_mesh()
    obj_path = os.path.join(out_dir, "sample_grooved_block.obj")
    mtl_path = os.path.join(out_dir, "sample_grooved_block.mtl")
    write_obj(vlist, faces, obj_path, os.path.basename(mtl_path))
    write_mtl(mtl_path)

    counts = {}
    for mat_id, _ in faces:
        counts[MATERIALS[mat_id][0]] = counts.get(MATERIALS[mat_id][0], 0) + 1
    print(f"vertices={len(vlist)} triangles={len(faces)}")
    for name, n in counts.items():
        print(f"  {name}: {n} triangles")
    print(f"wrote {obj_path}")
    print(f"wrote {mtl_path}")


if __name__ == "__main__":
    sys.exit(main())
